"""Tiny one-page PDF writer for the synthetic sample documents (no dependency; Helvetica, text and rules only).

The output is a valid PDF 1.4 file (correct xref offsets), so magic-byte detection and every PDF viewer accept it.
"""

from __future__ import annotations

from dataclasses import dataclass, field

PAGE_W, PAGE_H = 595, 842  # A4 in points


def _esc(text: str) -> str:
    # Helvetica (WinAnsi) has no rupee sign; write "Rs." instead.
    text = text.replace("₹", "Rs. ").replace("—", "-").replace("–", "-")
    text = text.encode("latin-1", "replace").decode("latin-1")
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


@dataclass
class Page:
    ops: list[str] = field(default_factory=list)

    def text(self, x: float, y: float, s: str, size: float = 11, bold: bool = False) -> None:
        font = "F2" if bold else "F1"
        self.ops.append(f"BT /{font} {size:g} Tf {x:g} {y:g} Td ({_esc(s)}) Tj ET")

    def rule(self, x1: float, y1: float, x2: float, y2: float, width: float = 0.8) -> None:
        self.ops.append(f"{width:g} w {x1:g} {y1:g} m {x2:g} {y2:g} l S")

    def box(self, x: float, y: float, w: float, h: float, grey: float = 0.93) -> None:
        self.ops.append(f"{grey:g} g {x:g} {y:g} {w:g} {h:g} re f 0 g")


def render(page: Page, title: str) -> bytes:
    content = "\n".join(page.ops).encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PAGE_W} {PAGE_H}] "
        "/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>".encode(),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
        b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
        f"<< /Title ({_esc(title)}) /Producer (FDR Portal demo seed) >>".encode("latin-1"),
    ]
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for n, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{n} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R /Info {len(objects)} 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


TITLES = {
    "FDR_COPY": "Fixed Deposit Receipt",
    "BANK_LETTER": "Bank confirmation letter",
    "DEPOSIT_CONFIRMATION": "Security deposit confirmation",
    "LIEN_LETTER": "Lien marking letter",
    "RELEASE_LETTER": "Request for release of deposit",
    "COMPLIANCE_CERTIFICATE": "Compliance certificate",
    "LIEN_REMOVAL_REQUEST": "Request for removal of lien",
    "OTHER": "Supporting document",
}


def sample_document(doc_type: str, rows: list[tuple[str, str]], institution: str, bank: str, note: str = "") -> bytes:
    """A synthetic bank document with the instrument's values printed in a table."""
    title = TITLES.get(doc_type, "Document")
    p = Page()
    p.box(40, 760, PAGE_W - 80, 52, 0.9)
    p.text(56, 790, bank, 16, bold=True)
    p.text(56, 772, "Demo Bank Letter - synthetic data, not a real bank document", 9)
    p.text(56, 725, title, 14, bold=True)
    p.text(56, 707, f"Account holder: {institution}", 10)
    p.rule(56, 695, PAGE_W - 56, 695)
    y = 672
    for label, value in rows:
        p.text(56, y, label, 10, bold=True)
        p.text(230, y, value, 11)
        y -= 24
    p.rule(56, y + 8, PAGE_W - 56, y + 8)
    if note:
        p.text(56, y - 14, note, 10)
    p.text(56, 120, "For the Branch Manager", 10)
    p.text(56, 104, "(signature and seal - synthetic)", 9)
    p.text(56, 60, "Generated by the FDR Portal demo seed for SIH26265. Contains no real customer data.", 8)
    return render(p, f"{title} - {bank}")
